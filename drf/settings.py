def _environment_bool(name, default):
    value = os.environ.get(name)
    if value is None:
        return default
    normalized = value.strip().lower()
    if normalized not in {'true', 'false'}:
        raise RuntimeError(f'{name} debe ser true o false.')
    return normalized == 'true'


